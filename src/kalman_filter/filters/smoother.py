r"""Module: kalman_filter.filters.smoother

Description: Rauch-Tung-Striebel (RTS) fixed-interval optimal backward smoother for
    linear and nonlinear state-space models. Fuses all forward and backward temporal
    information to produce minimum-variance smoothed trajectories.

Author: Hui Zhang
Date: 2026-11-23
Copyright: (c) 2026 Hui Zhang. All rights reserved.
"""

import logging

import numpy as np

from kalman_filter.models.base import StateSpaceModel
from kalman_filter.types import FilterResult, FloatArray, SmootherResult

logger = logging.getLogger(__name__)

__all__ = ["rts_smooth"]


def rts_smooth(
    filter_result: FilterResult,
    model: StateSpaceModel,
    controls: FloatArray | None = None,
) -> SmootherResult:
    r"""Runs the Rauch-Tung-Striebel (RTS) backward smoothing recursion.

    Given forward filtering results :math:`\{\hat{x}_{k|k}, P_{k|k}\}` and predictions
    :math:`\{\hat{x}_{k+1|k}, P_{k+1|k}\}`, computes backward smoothed beliefs:
    .. math::
        C_k = P_{k|k} F_k^T P_{k+1|k}^{-1} \\
        x_{k|T}^s = \hat{x}_{k|k} + C_k (x_{k+1|T}^s - \hat{x}_{k+1|k}) \\
        P_{k|T}^s = P_{k|k} + C_k (P_{k+1|T}^s - P_{k+1|k}) C_k^T

    Args:
        filter_result: Forward filtering history generated by ``filter.run()``.
        model: State-space model implementing ``StateSpaceModel``.
        controls: Optional control input sequence, shape ``(T, p)``.

    Returns:
        A ``SmootherResult`` containing smoothed means, covariances, and smoother gains.

    Raises:
        ValueError: If array dimensions are inconsistent.
    """
    T = filter_result.steps
    n = filter_result.state_dim

    smoothed_means = np.empty((T, n))
    smoothed_covs = np.empty((T, n, n))
    smoother_gains = np.empty((max(0, T - 1), n, n))

    # Initialize terminal step (k = T - 1) with final filter posterior
    smoothed_means[-1] = filter_result.filtered_means[-1].copy()
    smoothed_covs[-1] = filter_result.filtered_covs[-1].copy()

    # Backward pass from T - 2 down to 0
    for k in range(T - 2, -1, -1):
        u_k = None if controls is None else np.asarray(controls[k], dtype=float)

        # Transition Jacobian at the filtered mean
        if hasattr(model, "F"):
            F_k = np.asarray(model.F, dtype=float)
        else:
            filtered_x = filter_result.filtered_means[k]
            F_k = np.asarray(model.state_jacobian(filtered_x, u_k), dtype=float)


        P_pred_next = filter_result.predicted_covs[k + 1]
        P_filt_curr = filter_result.filtered_covs[k]

        # Smoother gain C_k = P_{k|k} F_k^T (P_{k+1|k})^{-1}
        # Solved via: C_k @ P_{k+1|k} = P_{k|k} @ F_k^T => (P_{k+1|k}^T) @ C_k^T = F_k @ P_{k|k}
        gain_T = np.linalg.solve(P_pred_next.T, F_k @ P_filt_curr)
        C_k = gain_T.T
        smoother_gains[k] = C_k

        # Smoothed state update
        err = smoothed_means[k + 1] - filter_result.predicted_means[k + 1]
        smoothed_means[k] = filter_result.filtered_means[k] + C_k @ err

        # Smoothed covariance update
        cov_err = smoothed_covs[k + 1] - P_pred_next
        P_smooth = P_filt_curr + C_k @ cov_err @ C_k.T
        smoothed_covs[k] = 0.5 * (P_smooth + P_smooth.T)

    return SmootherResult(
        smoothed_means=smoothed_means,
        smoothed_covs=smoothed_covs,
        smoother_gains=smoother_gains,
    )
